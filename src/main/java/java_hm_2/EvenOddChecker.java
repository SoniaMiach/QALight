package java_hm_2;

public class EvenOddChecker {
    public static void main(String[] args) {
        // If-else task 1. Checking if a inputNumber is even
        int inputNumber = 1;

        if (inputNumber % 2 == 0) {
            System.out.println("The inputNumber is even");
        } else {
            System.out.println("The inputNumber is odd");
        }
    }
}
