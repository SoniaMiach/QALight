package java_hm_2;

public class NumberComparator {
    public static void main(String[] args) {
        // If-else task 2. Determining the Larger of Two Numbers
        int a = 2;
        int b = 2;

        if (a > b) {
            System.out.println("A larger number: " + a);
        } else if (b > a) {
            System.out.println("A larger number: " + b);
        } else {
            System.out.println("Equal numbers");
        }
    }
}
