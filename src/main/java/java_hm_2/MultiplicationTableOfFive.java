package java_hm_2;

public class MultiplicationTableOfFive {
    //Loops.Task 4.Multiplication table for the number 5
    public static void main(String[] args) {
        int number = 5;
        for (int i = 1; i <= 10; i++) {
            System.out.println(number + " x " + i + " = " + (number * i));
        }
    }
}
